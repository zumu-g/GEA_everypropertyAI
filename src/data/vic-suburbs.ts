/** Look up a suburb entry by name (case-insensitive) */
export function findSuburb(name: string): SuburbEntry | undefined {
  const lower = name.toLowerCase();
  return VIC_SUBURBS.find((s) => s.name.toLowerCase() === lower);
}

/** Return all suburbs for a given postcode */
export function suburbsByPostcode(postcode: string): SuburbEntry[] {
  return VIC_SUBURBS.filter((s) => s.postcode === postcode);
}

/** Return all suburbs for a given LGA */
export function suburbsByLGA(lga: string): SuburbEntry[] {
  const lower = lga.toLowerCase();
  return VIC_SUBURBS.filter((s) => s.lga?.toLowerCase() === lower);
}
